const nodemailer = require('nodemailer');
const { env } = require('../config/env');
const logger = require('../utils/logger');

let transporter = null;

function getTransporter() {
  if (transporter) return transporter;

  if (!env.SMTP_HOST || !env.SMTP_USER) {
    logger.warn('⚠️ SMTP not configured. Emails will be logged to console.');
    return null;
  }

  transporter = nodemailer.createTransport({
    host: env.SMTP_HOST,
    port: env.SMTP_PORT,
    secure: env.SMTP_PORT === 465,
    auth: {
      user: env.SMTP_USER,
      pass: env.SMTP_PASS,
    },
  });

  return transporter;
}

async function sendEmail({ to, subject, html, text }) {
  const transport = getTransporter();

  if (!transport) {
    // Log to console in development
    logger.info('📧 [EMAIL - DEV MODE]', { to, subject, text: text?.substring(0, 100) });
    return { messageId: 'dev-mode', logged: true };
  }

  try {
    const info = await transport.sendMail({
      from: `"AI Content System" <${env.SMTP_FROM}>`,
      to,
      subject,
      html,
      text,
    });

    logger.info(`📧 Email sent: ${info.messageId}`, { to, subject });
    return info;
  } catch (err) {
    logger.error('Email send failed', { to, subject, error: err.message });
    // Don't throw — email failure shouldn't break the workflow
    return null;
  }
}

